if [ "$1" = "$2" ] || [ "$1" = "$3" ] || [ "$1" = "$4" ] || \
   [ "$2" = "$3" ] || [ "$2" = "$4" ] || \
   [ "$3" = "$4" ]; then
   echo "Ошибка: все параметры должны быть уникальными"
   echo "Параметры: \$1='$1', \$2='$2', \$3='$3', \$4='$4'"
   echo "Попробуйте снова."
   exit 1;
else
   ./getInfo.sh $1 $2 $3 $4
   exit 0;
fi